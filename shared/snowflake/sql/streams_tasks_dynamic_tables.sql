-- STAR
-- Situation: Lake files from multiple cloud providers need governed incremental loading into Snowflake.
-- Task: Define warehouse side objects that can be parameterized per cloud stage.
-- Action: Create file formats, staging tables, curated tables, streams, tasks, and merge logic.
-- Result: Enables incremental lake to warehouse processing without full reloads.

CREATE DATABASE IF NOT EXISTS PORTFOLIO_BIG_DATA;
CREATE SCHEMA IF NOT EXISTS PORTFOLIO_BIG_DATA.CURATED;

CREATE OR REPLACE FILE FORMAT PORTFOLIO_BIG_DATA.CURATED.JSON_GZIP_FORMAT
  TYPE = JSON
  COMPRESSION = GZIP
  STRIP_OUTER_ARRAY = FALSE;

CREATE OR REPLACE FILE FORMAT PORTFOLIO_BIG_DATA.CURATED.CSV_GZIP_FORMAT
  TYPE = CSV
  COMPRESSION = GZIP
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"';

CREATE OR REPLACE TABLE PORTFOLIO_BIG_DATA.CURATED.ORDER_BRONZE (
  RAW_RECORD VARIANT,
  SOURCE_FILE STRING,
  INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE PORTFOLIO_BIG_DATA.CURATED.ORDER_SILVER (
  ORDER_ID STRING NOT NULL,
  CUSTOMER_ID STRING NOT NULL,
  ORDER_TS TIMESTAMP_NTZ,
  AMOUNT NUMBER(18, 2),
  CURRENCY STRING,
  CHANNEL STRING,
  SOURCE_FILE STRING,
  INGESTED_AT TIMESTAMP_NTZ,
  UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE STREAM PORTFOLIO_BIG_DATA.CURATED.ORDER_BRONZE_STREAM
  ON TABLE PORTFOLIO_BIG_DATA.CURATED.ORDER_BRONZE
  APPEND_ONLY = TRUE;

CREATE OR REPLACE TASK PORTFOLIO_BIG_DATA.CURATED.MERGE_ORDER_SILVER_TASK
  WAREHOUSE = COMPUTE_WH
  SCHEDULE = 'USING CRON 0 * * * * UTC'
WHEN SYSTEM$STREAM_HAS_DATA('PORTFOLIO_BIG_DATA.CURATED.ORDER_BRONZE_STREAM')
AS
MERGE INTO PORTFOLIO_BIG_DATA.CURATED.ORDER_SILVER target
USING (
  SELECT
    RAW_RECORD:order_id::STRING AS ORDER_ID,
    RAW_RECORD:customer_id::STRING AS CUSTOMER_ID,
    TRY_TO_TIMESTAMP_NTZ(RAW_RECORD:order_ts::STRING) AS ORDER_TS,
    RAW_RECORD:amount::NUMBER(18, 2) AS AMOUNT,
    RAW_RECORD:currency::STRING AS CURRENCY,
    RAW_RECORD:channel::STRING AS CHANNEL,
    SOURCE_FILE,
    INGESTED_AT
  FROM PORTFOLIO_BIG_DATA.CURATED.ORDER_BRONZE_STREAM
) source
ON target.ORDER_ID = source.ORDER_ID
WHEN MATCHED THEN UPDATE SET
  CUSTOMER_ID = source.CUSTOMER_ID,
  ORDER_TS = source.ORDER_TS,
  AMOUNT = source.AMOUNT,
  CURRENCY = source.CURRENCY,
  CHANNEL = source.CHANNEL,
  SOURCE_FILE = source.SOURCE_FILE,
  UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
  ORDER_ID, CUSTOMER_ID, ORDER_TS, AMOUNT, CURRENCY, CHANNEL, SOURCE_FILE, INGESTED_AT
) VALUES (
  source.ORDER_ID, source.CUSTOMER_ID, source.ORDER_TS, source.AMOUNT, source.CURRENCY,
  source.CHANNEL, source.SOURCE_FILE, source.INGESTED_AT
);
